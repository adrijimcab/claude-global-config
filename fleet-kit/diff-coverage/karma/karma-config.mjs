/**
 * The Karma configuration a graded run uses, written into the run's own directory — never into the
 * repository. It loads the project's real base configuration, then changes exactly three things for this
 * run: coverage goes to the run directory as `lcovonly`, the coverage THRESHOLDS are dropped (so
 * pre-existing debt elsewhere cannot fail the process for a reason unrelated to the diff), and the
 * console reporter is `progress`, whose summary line `karma-summary.mjs` reads.
 *
 * TWO BASES. A project whose `angular.json` test target names a `karmaConfig` is loaded from that file.
 * A project that names none runs Angular's BUILT-IN config, which is a function inside
 * `@angular-devkit/build-angular` that is not exported — so this module mirrors it (frameworks, plugins,
 * launcher) for the one major it was read from, {@link MIRRORED_ANGULAR_MAJOR}, and REFUSES any other
 * major. An upgrade is then a loud "re-derive the mirror", never a silently different harness.
 *
 * @es La configuración de Karma de una corrida calificada, escrita en el directorio de la corrida, nunca
 * en el repositorio. Carga la base real del proyecto y cambia solo tres cosas: la cobertura va al
 * directorio de la corrida como `lcovonly`, se quitan los UMBRALES, y el reporter es `progress`. Si el
 * proyecto no nombra `karmaConfig`, corre la config INTEGRADA de Angular, que no se exporta: aquí se
 * refleja para la versión mayor de la que se leyó, y cualquier otra mayor se RECHAZA.
 */

import { existsSync, readFileSync } from 'node:fs';
import path from 'node:path';

export const BUILTIN = 'angular-builtin';

/** The `@angular-devkit/build-angular` major the built-in mirror was read from (19.2.22). @es La versión mayor reflejada. */
export const MIRRORED_ANGULAR_MAJOR = 19;

/**
 * Why the built-in mirror cannot be used for `workspaceDir`, or `undefined` when it can.
 * @es Por qué no se puede usar el espejo integrado, o `undefined`.
 */
export function builtinMirrorProblem(workspaceDir) {
  const manifest = path.join(workspaceDir, 'node_modules', '@angular-devkit', 'build-angular', 'package.json');

  if (!existsSync(manifest)) return `@angular-devkit/build-angular is not installed in ${workspaceDir}`;

  const version = String(JSON.parse(readFileSync(manifest, 'utf8')).version);
  const major = Number(version.split('.')[0]);

  if (major !== MIRRORED_ANGULAR_MAJOR) return `the built-in Karma mirror was read from @angular-devkit/build-angular ${MIRRORED_ANGULAR_MAJOR}.x, and ${workspaceDir} has ${version} — re-derive the mirror before grading`;

  return undefined;
}

/** The base-config expression of the generated file. @es La expresión de la config base del fichero generado. */
function baseExpression(workspaceDir, baseConfig) {
  if (baseConfig !== BUILTIN) return `require(${JSON.stringify(path.join(workspaceDir, baseConfig))})`;

  return `function angularBuiltin(config) {
  // Mirror of @angular-devkit/build-angular ${MIRRORED_ANGULAR_MAJOR}.x getBuiltInKarmaConfig (browser builder).
  config.set({
    basePath: '',
    frameworks: ['jasmine', '@angular-devkit/build-angular'],
    plugins: ['karma-jasmine', 'karma-chrome-launcher', 'karma-jasmine-html-reporter', 'karma-coverage', '@angular-devkit/build-angular/plugins/karma'].map((plugin) => workspaceRequire(plugin)),
    jasmineHtmlReporter: { suppressAll: true },
    browsers: ['ChromeHeadless'],
    customLaunchers: { ChromeHeadlessNoSandbox: { base: 'ChromeHeadless', flags: ['--no-sandbox', '--headless', '--disable-gpu', '--disable-dev-shm-usage'] } }
  });
}`;
}

/**
 * The folder Karma would have resolved `basePath: ''` against in the project's own run: the base config
 * file's folder, or the workspace for the built-in config (which Angular passes as an object).
 * @es La carpeta contra la que Karma habría resuelto `basePath: ''` en la corrida propia del proyecto.
 */
export const basePathOf = (workspaceDir, baseConfig) => (baseConfig === BUILTIN ? workspaceDir : path.dirname(path.join(workspaceDir, baseConfig)));

/**
 * The source of the per-run Karma config file.
 * @param options `{ workspaceDir, baseConfig, coverageDir }` — absolute paths; `baseConfig` is
 *   workspace-relative or {@link BUILTIN}.
 * @es El código del fichero de config de Karma de una corrida.
 */
export function karmaConfigSource({ workspaceDir, baseConfig, coverageDir }) {
  return `// Generated by fleet-kit diff-coverage for ONE run. Never edited, never reused.
'use strict';
const path = require('node:path');
const { createRequire } = require('node:module');
const workspaceRequire = createRequire(path.join(${JSON.stringify(workspaceDir)}, 'package.json'));
const base = ${baseExpression(workspaceDir, baseConfig)};

module.exports = function gradedRun(config) {
  base(config);
  // Karma resolves basePath against the config FILE's folder; this file lives in the run directory, so
  // the base's own folder is restored explicitly.
  config.set({ basePath: ${JSON.stringify(basePathOf(workspaceDir, baseConfig))}, reporters: ['progress'] });
  config.coverageReporter = { dir: ${JSON.stringify(coverageDir)}, subdir: '.', reporters: [{ type: 'lcovonly' }, { type: 'text-summary' }] };
};
`;
}
